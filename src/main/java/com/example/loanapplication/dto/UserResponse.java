package com.example.loanapplication.dto;
import java.time.LocalDateTime;
/*
 * MILESTONE 1: USER MANAGEMENT
 * Step 3: Create User Response DTO
 *
 * Represents the data returned to the client after operations such as creating a new user or retrieving an existing user.
 *
 * NOTE:
 * DTOs are not explicitly mentioned in the Month 2 assignment. Implemented additionally to separate API response data from the JPA Entity.
 * DTO -> A DTO (Data Transfer Object) is an object used to transfer data between different layers or systems without exposing the internal entity directly.
 *
 * Request DTO: Controls what data the client can send.
 * Response DTO: Controls what data the API returns.
 */

public class UserResponse {

    //User's unique ID generated by the database.
    private Long id;

    //User's name returned to the client.
    private String name;

    //User's email returned to the client.
    private String email;

    //User's phone number returned to the client.
    private String phoneNumber;

    //Date and time when the user was created.
    private LocalDateTime createdAt;

    /*
     * No-argument constructor.
     * Allows Jackson to create an empty UserResponse object when converting a Java object into JSON (serialization).
     * Jackson uses the getters to retrieve the field values and include them in the outgoing JSON response.
     */
    public UserResponse() {}

    /*
     * Parameterized constructor.
     * Allows the service layer to create a UserResponse object by passing all required response fields at once.
     */
    public UserResponse(Long id, String name, String email,
                        String phoneNumber, LocalDateTime createdAt) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.phoneNumber = phoneNumber;
        this.createdAt = createdAt;
    }

    //Getter to retrieve user's ID.
    public Long getId() {
        return id;
    }

    //Getter to retrieve user's name.
    public String getName() {
        return name;
    }

    //Getter to retrieve user's email.
    public String getEmail() {
        return email;
    }

    //Getter to retrieve user's phone number.
    public String getPhoneNumber() {
        return phoneNumber;
    }

    //Getter to retrieve user's creation timestamp.
    public LocalDateTime getCreatedAt() {
        return createdAt;
    }
}
